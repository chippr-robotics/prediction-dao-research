/**
 * Cross-device passkey sign-in (issue: "passkey does not have an account on this device").
 *
 * The problem
 * -----------
 * A member creates a passkey on their phone and opens the app on a laptop. The passkey itself is
 * synced (iCloud Keychain / Google Password Manager) and the WebAuthn ceremony succeeds — but the
 * app could not tell WHICH account it belonged to, because:
 *
 *   - the account address lived only in this browser's localStorage, which is empty on a new device
 *   - a WebAuthn assertion returns a credential id and a signature, but NOT the public key
 *   - the address is derived FROM the public key, so with no key there is no address
 *
 * Why not just put the key in `user.id`?
 * --------------------------------------
 * `user.id` is the obvious carrier — it comes back as `userHandle` on any device. It cannot work
 * here: `user.id` must be supplied to `navigator.credentials.create()`, but the P-256 key pair is
 * generated BY the authenticator during that same call, so the key does not exist yet. And FairWins
 * has no backend (constitution: no-backend footprint), so there is no server-side map from
 * credential id to account either. Existing passkeys already carry 16 random bytes there regardless.
 *
 * The approach
 * ------------
 * Recover the public key from the signature itself. ECDSA permits public-key recovery, so the key
 * the app is missing is derivable from a ceremony the member already performs.
 *
 * ⚠️ THE SAFETY PROPERTY THAT SHAPES THIS WHOLE MODULE: a single signature is ALWAYS ambiguous.
 * Every (r, s) is verified by exactly TWO distinct public keys — measured at 200/200 over random
 * signatures, because it is inherent to ECDSA, not a quirk. Those two keys derive two DIFFERENT
 * account addresses. Picking the wrong one hands the member an address they can be told to fund and
 * from which nothing can ever be spent. So this module NEVER resolves from one signature.
 *
 * Two assertions over different challenges each yield two candidates; the true key is the one in
 * BOTH sets, and the decoys differ because they depend on the message. The intersection is exactly
 * one key. That costs a second authenticator prompt, which callers must disclose — it happens once
 * per device, after which the key is cached locally like any other credential record.
 */

import { p256 } from '@noble/curves/nist.js'
import { sha256 } from '@noble/hashes/sha2.js'

import { getAssertion } from './credentials'

/** Curve order — needed to reject out-of-range DER integers. */
const CURVE_N = p256.Point?.Fn?.ORDER ?? p256.CURVE.n

export class CrossDeviceRecoveryFailed extends Error {
  constructor(message) {
    super(
      message ||
        'This passkey could not be matched to an account on this device. Sign in on the device where ' +
          'it was created, or use a linked wallet to recover access.'
    )
    this.name = 'CrossDeviceRecoveryFailed'
  }
}

/**
 * Decode a WebAuthn ECDSA signature (ASN.1 DER `SEQUENCE { INTEGER r, INTEGER s }`) into r/s.
 *
 * WebAuthn transmits DER, never raw r||s — treating the 64 trailing bytes as r||s appears to work
 * on signatures where neither integer needs a leading sign byte and fails intermittently otherwise,
 * which is the worst possible failure shape. DER INTEGERs are signed, so a value whose top bit is
 * set is prefixed with 0x00; that padding must be stripped, and short values must NOT be assumed
 * to be 32 bytes.
 */
export function derToRS(der) {
  const buf = der instanceof Uint8Array ? der : new Uint8Array(der)
  let i = 0
  if (buf[i++] !== 0x30) throw new CrossDeviceRecoveryFailed('Malformed signature (no DER SEQUENCE).')
  let seqLen = buf[i++]
  if (seqLen & 0x80) {
    const n = seqLen & 0x7f
    seqLen = 0
    for (let k = 0; k < n; k++) seqLen = (seqLen << 8) | buf[i++]
  }
  const readInt = () => {
    if (buf[i++] !== 0x02) throw new CrossDeviceRecoveryFailed('Malformed signature (no DER INTEGER).')
    const len = buf[i++]
    let v = buf.subarray(i, i + len)
    i += len
    while (v.length > 1 && v[0] === 0x00) v = v.subarray(1) // strip the sign byte
    let out = 0n
    for (const b of v) out = (out << 8n) | BigInt(b)
    return out
  }
  const r = readInt()
  const s = readInt()
  if (r <= 0n || s <= 0n || r >= CURVE_N || s >= CURVE_N) {
    throw new CrossDeviceRecoveryFailed('Signature values out of range.')
  }
  return { r, s }
}

/**
 * The message a WebAuthn authenticator actually signs:
 *   sha256( authenticatorData || sha256(clientDataJSON) )
 * `authenticatorData` must be the RAW bytes as returned — re-serialising or trimming it changes the
 * hash and every recovered key is then wrong (but still internally consistent, so it fails silently).
 */
export function webauthnSignedHash({ authenticatorData, clientDataJSON }) {
  const ad = authenticatorData instanceof Uint8Array ? authenticatorData : new Uint8Array(authenticatorData)
  const cd = clientDataJSON instanceof Uint8Array ? clientDataJSON : new Uint8Array(clientDataJSON)
  const joined = new Uint8Array(ad.length + 32)
  joined.set(ad, 0)
  joined.set(sha256(cd), ad.length)
  return sha256(joined)
}

const toHexXY = (point) => {
  const bytes = point.toBytes ? point.toBytes(false) : point.toRawBytes(false)
  return `0x${Array.from(bytes.subarray(1), (b) => b.toString(16).padStart(2, '0')).join('')}`
}

/**
 * Every public key that verifies this assertion. Expect TWO — see the module note. A candidate is
 * kept only if the signature genuinely verifies under it, which discards the bogus points that
 * recovery can produce for some recovery-bit values.
 *
 * Returns 0x-prefixed 64-byte `x||y` strings, the same encoding `publicKeyToOwnerBytes` produces
 * and the account contract stores, so they compare byte-for-byte against `ownerAtIndex`.
 */
export function recoverCandidateKeys({ authenticatorData, clientDataJSON, signature }) {
  const hash = webauthnSignedHash({ authenticatorData, clientDataJSON })
  const { r, s } = derToRS(signature)
  // @noble/curves v2 takes the signature as BYTES; passing the {r,s} object throws. That throw
  // would land in the catch below — which exists for invalid recovery bits — leaving `found`
  // empty and turning "this key signed it" into "no candidate", silently. Encode once, up front.
  const sigInstance = new p256.Signature(r, s)
  const sigBytes = sigInstance.toBytes ? sigInstance.toBytes('compact') : sigInstance.toCompactRawBytes()
  const found = new Set()
  for (const bit of [0, 1, 2, 3]) {
    try {
      const point = new p256.Signature(r, s, bit).recoverPublicKey(hash)
      const bytes = point.toBytes ? point.toBytes(false) : point.toRawBytes(false)
      // lowS:false — authenticators are not required to emit low-S, and rejecting high-S here
      // would silently drop the true key for those devices.
      // prehash:false — `hash` IS the digest the authenticator signed
      // (sha256(authenticatorData || sha256(clientDataJSON))). @noble/curves v2 prehashes by
      // DEFAULT, where v1 did not; leaving it on would hash the digest a second time and every
      // candidate would fail to verify, emptying the set exactly like the {r,s} throw above.
      if (p256.verify(sigBytes, hash, bytes, { lowS: false, prehash: false })) found.add(toHexXY(point))
    } catch {
      // Not every recovery bit yields a valid point; that is expected.
    }
  }
  return [...found]
}

/**
 * Resolve the ONE public key behind a credential, using two assertions.
 *
 * `first` is an already-completed assertion (callers have usually just run one to learn the
 * credential id). The second is pinned to that same credential id so the member is not offered a
 * chooser again and cannot accidentally authenticate a different passkey — which would intersect to
 * nothing, or worse, to a key belonging to neither ceremony.
 *
 * Throws rather than guessing: an empty or multi-key intersection means the app does not know the
 * account, and inventing one is how a member loses funds to an address nobody controls.
 */
export async function recoverPublicKey({ first, credentialId, deps = {} } = {}) {
  if (!first) throw new CrossDeviceRecoveryFailed('No assertion to recover from.')
  const firstSet = recoverCandidateKeys(first)
  if (firstSet.length === 0) throw new CrossDeviceRecoveryFailed('Could not read the passkey signature.')

  const id = credentialId ?? first.credentialId
  const second = await (deps.getAssertion ?? getAssertion)({
    challenge: (deps.randomChallenge ?? (() => crypto.getRandomValues(new Uint8Array(32))))(),
    credentialId: id,
    deps,
  })
  if (second.credentialId && id && second.credentialId !== id) {
    throw new CrossDeviceRecoveryFailed('A different passkey was used for the second confirmation.')
  }

  const secondSet = new Set(recoverCandidateKeys(second))
  const both = firstSet.filter((k) => secondSet.has(k))
  if (both.length !== 1) {
    throw new CrossDeviceRecoveryFailed(
      both.length === 0
        ? 'The two passkey confirmations did not match.'
        : 'This passkey could not be identified unambiguously.'
    )
  }
  const xy = both[0]
  return { ownerBytes: xy, publicKey: { x: `0x${xy.slice(2, 66)}`, y: `0x${xy.slice(66, 130)}` } }
}

export default recoverPublicKey
