#!/usr/bin/env node
/**
 * Generate the Google uptime prober allowlist (spec 086, T024 / FR-040).
 *
 * WHY THIS EXISTS
 * Cloudflare publishes its egress ranges and the Terraform provider exposes them as a data source,
 * so a change there surfaces as a reviewable firewall diff on the next plan. Google's uptime prober
 * addresses have NO such data source — `infra/vm/provision.sh` shelled out to
 * `gcloud monitoring uptime list-ips` at provision time and never looked again.
 *
 * A pinned copy that nobody re-checks fails in the worst way: the probers move, the checks go red
 * against a healthy origin, and the team learns to ignore the alert. So the list is generated into a
 * committed, dated file, and the drift job re-runs this in --check mode and FAILS when the committed
 * copy no longer matches. Staleness becomes loud instead of silently wrong.
 *
 * Usage:
 *   node scripts/infra/generate-prober-cidrs.js            # write the file
 *   node scripts/infra/generate-prober-cidrs.js --check    # exit 1 if the committed copy is stale
 *
 * Requires an authenticated `gcloud`. Without one it exits non-zero and says so — it never writes a
 * partial or empty list, because an empty allowlist would silently lock every prober out.
 */
const fs = require("fs");
const path = require("path");
const { execFileSync } = require("child_process");

const ROOT = path.resolve(__dirname, "..", "..");
const TARGETS = [
  path.join(ROOT, "infra", "terraform", "environments", "prod", "prober-cidrs.json"),
  path.join(ROOT, "infra", "terraform", "environments", "staging", "prober-cidrs.json"),
];

function fetchProberIps() {
  let raw;
  try {
    raw = execFileSync("gcloud", ["monitoring", "uptime", "list-ips", "--format=value(ipAddress)"], {
      encoding: "utf8",
      stdio: ["ignore", "pipe", "pipe"],
    });
  } catch (err) {
    throw new Error(
      `could not run 'gcloud monitoring uptime list-ips'. An authenticated gcloud is required.\n${err.message}`
    );
  }

  const cidrs = raw
    .split("\n")
    .map((l) => l.trim())
    .filter(Boolean)
    .map((ip) => (ip.includes("/") ? ip : `${ip}/32`))
    .sort();

  // An empty list would produce a firewall rule that admits nothing, locking every prober out while
  // looking like a successful run. Refuse rather than write it.
  if (cidrs.length === 0) throw new Error("gcloud returned no prober addresses — refusing to write an empty allowlist");

  return [...new Set(cidrs)];
}

function render(cidrs) {
  return `${JSON.stringify(
    {
      _comment:
        "Generated by scripts/infra/generate-prober-cidrs.js. Do not edit by hand. Google publishes no Terraform data source for these addresses, so the drift job regenerates this and fails when it is stale.",
      generated_at: new Date().toISOString().slice(0, 10),
      source: "gcloud monitoring uptime list-ips",
      count: cidrs.length,
      cidrs,
    },
    null,
    2
  )}\n`;
}

function main(argv) {
  const checkOnly = argv.includes("--check");
  let cidrs;
  try {
    cidrs = fetchProberIps();
  } catch (err) {
    console.error(`prober-cidrs: ${err.message}`);
    return 1;
  }

  let stale = false;
  for (const target of TARGETS) {
    const next = render(cidrs);

    if (checkOnly) {
      if (!fs.existsSync(target)) {
        console.error(`prober-cidrs: ${path.relative(ROOT, target)} is missing`);
        stale = true;
        continue;
      }
      // Compare the address list only. `generated_at` changes on every run and is not drift.
      const current = JSON.parse(fs.readFileSync(target, "utf8"));
      if (JSON.stringify(current.cidrs) !== JSON.stringify(cidrs)) {
        console.error(
          `prober-cidrs: ${path.relative(ROOT, target)} is STALE.\n` +
            `  committed: ${current.cidrs.length} addresses\n` +
            `  live:      ${cidrs.length} addresses\n` +
            "  Re-run `node scripts/infra/generate-prober-cidrs.js` and commit the result. Until then " +
            "the firewall admits a prober set Google no longer uses, and uptime checks can go red " +
            "against a healthy origin."
        );
        stale = true;
      }
      continue;
    }

    fs.mkdirSync(path.dirname(target), { recursive: true });
    fs.writeFileSync(target, next);
    console.log(`prober-cidrs: wrote ${cidrs.length} addresses to ${path.relative(ROOT, target)}`);
  }

  if (checkOnly && !stale) console.log(`prober-cidrs: current (${cidrs.length} addresses)`);
  return stale ? 1 : 0;
}

if (require.main === module) process.exit(main(process.argv.slice(2)));

module.exports = { render };
